let efectividadPases = 10;

console.log("--------------------------------------------------");
console.log("📊 AJUSTE DINÁMICO DE ASIGNACIÓN EN CAMPO");
console.log("--------------------------------------------------");

// Suma compuesta: Se consolida el bloque de pases cortos del primer tiempo (+5)
efectividadPases += 5;
console.log(`Pases tras consolidación ofensiva (Suma): ${efectividadPases}`);

// Resta compuesta: Se descuentan las pérdidas de balón en transiciones (-3)
efectividadPases -= 3;
console.log(`Pases tras pérdidas por presión (Resta): ${efectividadPases}`);

// Multiplicación compuesta: Se duplica el factor por efectividad en pases filtrados (*2)
efectividadPases *= 2;
console.log(`Coeficiente por pases de alta precisión (Multiplicación): ${efectividadPases}`);

// División compuesta: Se pondera la métrica dividiendo entre los 4 sectores del terreno de juego (/4)
efectividadPases /= 4;
console.log(`Índice distribuido por cuadrante táctico (División): ${efectividadPases}`);

// Módulo compuesto: Se calcula el residuo logístico del flujo de pases en el último tercio (%4)
efectividadPases %= 4;
console.log(`Residuo estructural de posesión residual (Módulo): ${efectividadPases}`);

// Potencia compuesta: Proyección exponencial de desgaste físico según los bloques de posesión (**3)
efectividadPases **= 3;

console.log("--------------------------------------------------");
console.log("📈 EVALUACIÓN FINAL DEL MOTOR ESTADÍSTICO");
console.log("--------------------------------------------------");
console.log(`Métrica final consolidada en FutData Core: ${efectividadPases}`);
console.log("--------------------------------------------------");